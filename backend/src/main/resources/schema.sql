CREATE TABLE IF NOT EXISTS search_requests (
    id             UUID                     PRIMARY KEY,
    thesis         VARCHAR(2000)            NOT NULL,
    reason         VARCHAR(5000)            NOT NULL,
    status         VARCHAR(20)              NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    search_query   VARCHAR(5000),
    gmu_search_url VARCHAR(10000),
    error_message  VARCHAR(2000)
);

ALTER TABLE search_requests ADD COLUMN IF NOT EXISTS search_query VARCHAR(5000);
ALTER TABLE search_requests ADD COLUMN IF NOT EXISTS gmu_search_url VARCHAR(10000);
ALTER TABLE search_requests ADD COLUMN IF NOT EXISTS error_message VARCHAR(2000);

CREATE TABLE IF NOT EXISTS search_sources (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id    UUID          NOT NULL,
    sort_order    INT           NOT NULL,
    title         VARCHAR(2000) NOT NULL,
    authors       VARCHAR(4000),
    pub_year      VARCHAR(20),
    journal       VARCHAR(1000),
    abstract_text VARCHAR(100000),
    doi           VARCHAR(500),
    link_url      VARCHAR(4000),
    FOREIGN KEY (request_id) REFERENCES search_requests (id) ON DELETE CASCADE
);
